# Auto Sync Website to GitHub
# Project: Webiste-idoed
# Monitors all project files and pushes changes safely.

$ErrorActionPreference = "Stop"

$ProjectPath = "C:\Users\ACER\Downloads\Webiste-idoed"
$Branch = "main"
$Remote = "origin"
$DebounceSeconds = 3

Set-Location $ProjectPath

Write-Host "======================================" -ForegroundColor Cyan
Write-Host " AUTO SYNC WEBSITE TO GITHUB" -ForegroundColor Cyan
Write-Host "======================================" -ForegroundColor Cyan
Write-Host "Folder: $ProjectPath"
Write-Host "Branch: $Branch"
Write-Host "Tekan Ctrl+C untuk menghentikan."
Write-Host ""

function Sync-Project {
    Set-Location $ProjectPath

    # Do not commit during an unfinished merge or rebase.
    $gitState = git status --porcelain
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Gagal membaca status Git." -ForegroundColor Red
        return
    }

    $mergeInProgress = Test-Path (Join-Path $ProjectPath ".git\MERGE_HEAD")
    $rebaseInProgress = (Test-Path (Join-Path $ProjectPath ".git\rebase-merge")) -or
                        (Test-Path (Join-Path $ProjectPath ".git\rebase-apply"))

    if ($mergeInProgress -or $rebaseInProgress) {
        Write-Host "Ada proses merge/rebase. Sinkronisasi ditunda." -ForegroundColor Yellow
        return
    }

    if (-not $gitState) {
        return
    }

    Write-Host "Perubahan terdeteksi. Memeriksa GitHub..." -ForegroundColor Yellow

    git fetch $Remote
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Fetch gagal. Periksa koneksi internet." -ForegroundColor Red
        return
    }

    # Stop instead of overwriting or force-pushing if branches diverge.
    $aheadBehind = git rev-list --left-right --count "HEAD...$Remote/$Branch"
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Gagal memeriksa riwayat remote." -ForegroundColor Red
        return
    }

    $counts = $aheadBehind -split "\s+"
    $ahead = [int]$counts[0]
    $behind = [int]$counts[1]

    if ($behind -gt 0) {
        Write-Host "GitHub memiliki commit yang belum ada di laptop." -ForegroundColor Yellow
        Write-Host "Sinkronisasi otomatis dihentikan agar tidak menimpa perubahan."
        Write-Host "Periksa dengan: git status"
        return
    }

    git add -A
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Gagal menambahkan perubahan." -ForegroundColor Red
        return
    }

    # Recheck after staging.
    $staged = git diff --cached --quiet
    if ($LASTEXITCODE -eq 0) {
        return
    }

    $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    git commit -m "Auto-sync website: $timestamp"
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Commit gagal. Periksa pesan Git di atas." -ForegroundColor Red
        return
    }

    git push $Remote $Branch
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Push gagal. Periksa status Git sebelum mencoba lagi." -ForegroundColor Red
        return
    }

    Write-Host "Perubahan berhasil dikirim ke GitHub!" -ForegroundColor Green
}

$watcher = New-Object System.IO.FileSystemWatcher
$watcher.Path = $ProjectPath
$watcher.IncludeSubdirectories = $true
$watcher.NotifyFilter = [System.IO.NotifyFilters]'FileName, DirectoryName, LastWrite, Size'
$watcher.EnableRaisingEvents = $true

$events = @("Changed", "Created", "Deleted", "Renamed")
foreach ($eventName in $events) {
    Register-ObjectEvent -InputObject $watcher -EventName $eventName -SourceIdentifier "WebsiteSync_$eventName" | Out-Null
}

Write-Host "Pemantau aktif. Simpan file untuk memulai sinkronisasi." -ForegroundColor Green

try {
    while ($true) {
        $event = Wait-Event -Timeout 2

        if ($null -ne $event) {
            # Drain duplicate events generated by editors and file copies.
            Start-Sleep -Seconds $DebounceSeconds
            Get-Event | Remove-Event -ErrorAction SilentlyContinue

            $changedPath = $event.SourceEventArgs.FullPath

            # Ignore Git internal files and this automation script itself.
            if (
                $changedPath -like "$ProjectPath\.git\*" -or
                $changedPath -ieq "$ProjectPath\auto-sync.ps1"
            ) {
                continue
            }   
            Sync-Project
        }
    }
}
finally {
    $watcher.EnableRaisingEvents = $false
    foreach ($eventName in $events) {
        Unregister-Event -SourceIdentifier "WebsiteSync_$eventName" -ErrorAction SilentlyContinue
    }
    Get-Event | Remove-Event -ErrorAction SilentlyContinue
    $watcher.Dispose()
}